/** 站点名称：英文界面且设置了 site_name_en 时用英文名，否则回退中文名 */
function site_name(): string {
    $name = get_pref(0, 'site_name', '思维简约导航');
    if (i18n_lang() === 'en') {
        $en = get_pref(0, 'site_name_en', '');
        if ($en !== '') return $en;
    }
    return $name;
}

function t(string $key): string {
    static $d = null;
    if ($d === null) {
        $all = i18n_dict();
        $d = $all[i18n_lang()] ?? $all['zh-CN'];
    }
    return $d[$key] ?? $key;
}
