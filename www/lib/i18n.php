/** 无显式设置时按 Accept-Language 优先级识别（zh 或 en），缺省 zh-CN */
function i18n_detect(): string {
    $al = $_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? '';
    foreach (explode(',', $al) as $part) {
        $tag = strtolower(trim(explode(';', $part)[0]));
        if ($tag === '') continue;
        if (str_starts_with($tag, 'en')) return 'en';
        if (str_starts_with($tag, 'zh')) return 'zh-CN';
    }
    return 'zh-CN';
}

function i18n_lang(): string {
    static $l = null;
    if ($l === null) {
        // 预览/分享用：URL ?lang=en|zh 无状态覆盖（优先于站点设置与浏览器识别）
        $q = $_GET['lang'] ?? '';
        if ($q === 'en' || $q === 'zh' || $q === 'zh-CN') { $l = $q === 'zh' ? 'zh-CN' : $q; return $l; }
        $raw = get_pref(0, 'lang', '');
        $l = $raw === 'en' || $raw === 'zh-CN' ? $raw : i18n_detect();   // 空/auto = 跟随浏览器
    }
    return $l;
}

